//! WebSocket event bus — the live stream the chat UI subscribes to.
//!
//! Wire shape matches `spec/asyncapi.yaml`:
//!
//! - `chat.message_inbound` / `chat.message_outbound` — user and agent text
//! - `chat.token_delta` — streaming assistant tokens
//! - `agent.tool_use` / `agent.tool_result` — every tool call
//! - `conversation.phase_changed` — FSM transitions
//! - `alert.*` — operational alerts
//!
//! Publishers call [`broadcast`] with a typed payload; the WebSocket
//! handler ([`stream_handler`]) forwards serialized events to every
//! connected subscriber.
//!
//! **No cloud dependencies.** `tokio::sync::broadcast` in-process only.

use axum::extract::State;
use axum::extract::ws::{Message, WebSocket, WebSocketUpgrade};
use axum::response::IntoResponse;
use serde::{Deserialize, Serialize};
use tokio::sync::broadcast;
use tracing::{debug, warn};

use crate::state::AppState;

/// Every event surface-able to the UI. Additive — new variants land
/// without breaking subscribers since the UI tolerates unknown kinds.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum UiEvent {
    /// Heartbeat so the client can detect dead connections.
    Ping {
        ts: i64,
    },

    /// User sent a message to a conversation.
    ChatMessageInbound {
        conversation_id: String,
        seq: i64,
        text: String,
        sender: Option<String>,
    },
    /// Agent text reply (full, non-streaming).
    ChatMessageOutbound {
        conversation_id: String,
        seq: i64,
        text: String,
    },
    /// Incremental token during a streaming turn.
    ChatTokenDelta {
        conversation_id: String,
        text: String,
    },

    AgentToolUse {
        conversation_id: String,
        seq: i64,
        tool_name: String,
        ordinal: u32,
    },
    AgentToolResult {
        conversation_id: String,
        seq: i64,
        ordinal: u32,
        ok: bool,
    },

    /// Live "what's the agent doing right now" pulse, fired the
    /// instant the runner emits a tool-call request and again when
    /// it resolves. Carries a human-readable `label` (e.g.
    /// "Searching the web for 'paris weather forecast today'")
    /// generated by `chats::humanise_tool_call` so the SPA's loader
    /// shows progress without having to know about every tool's
    /// args shape.
    ///
    /// Distinct from `AgentToolUse` (which is the persisted
    /// `tool_use` event-log row's broadcast) because the
    /// activity-pulse fires BEFORE the dispatch round-trip and
    /// again AFTER — `AgentToolUse` only lands once the runner
    /// commits the model_turn at end-of-turn.
    AgentToolActivity {
        conversation_id: String,
        /// Raw tool name (e.g. `web_search`, `calendar.list_events`).
        /// Drives icon selection on the SPA side.
        tool_name: String,
        /// Operator-facing one-liner. Always English-ish, generated
        /// from (tool_name, args) by `humanise_tool_call`. Falls
        /// back to "Running <tool_name>…" for tools without a
        /// custom humaniser entry.
        label: String,
        /// `"started"` when the agent issued the call;
        /// `"finished"` when the result is back (regardless of
        /// success — the SPA's loader just clears either way).
        status: String,
    },

    ConversationPhaseChanged {
        conversation_id: String,
        phase: String,
    },

    AlertFired {
        alert_id: String,
        severity: String,
        source: String,
        title: String,
    },
    AlertResolved {
        alert_id: String,
    },

    /// A routine run-history row's status changed (queued, picked up,
    /// finished). Drives live updates in the Settings → Routines
    /// run-history drawer so the operator doesn't have to refresh
    /// after a manual fire or to watch a scheduled fire complete.
    RoutineRunChanged {
        routine_id: String,
        run_id: String,
        /// Mirrors `RoutineRunStatus` — one of "Pending" | "Success"
        /// | "Failed" | "Skipped".
        status: String,
    },

    // ---- Phase 13.B — voice session lifecycle ----------------
    /// A voice session opened — first frame for the given session
    /// id arrived. Consumed by the SPA to render a "live mic" UX.
    VoiceSessionStarted {
        session: String,
        codec: String,
        sample_rate: u32,
    },
    /// A voice session ended either because the operator hit stop
    /// or because the server's stale-session reaper aged it out.
    VoiceSessionEnded {
        session: String,
        /// One of "operator_stopped" | "stale_reap" |
        /// "transport_closed".
        reason: String,
    },
    /// Streaming partial transcript. The Whisper adapter (Phase
    /// 13.C) feeds these as text accumulates; SPA renders them
    /// inline with the typing-indicator UX.
    VoiceTranscript {
        session: String,
        seq: u32,
        text: String,
        /// True when the segment is the final transcript (the
        /// endpointer fired and the LLM call is being dispatched).
        /// SPA uses this to commit the partial to the chat log.
        is_final: bool,
    },
    /// Outbound TTS audio chunk for the SPA to play. Phase 13.C
    /// fills these with real Kokoro output; today this variant
    /// exists so the SPA's WS handler can be wired ahead of the
    /// adapter landing.
    VoiceAudioOutbound {
        session: String,
        seq: u32,
        /// Codec the bytes are encoded in. SPA's audio pipeline
        /// picks the right MediaSource decoder.
        codec: String,
        /// base64 of the codec payload — keeps the WS event JSON
        /// inspectable in dev tools. Binary out lands when the
        /// SPA's audio pipeline is ready for raw frames.
        audio_b64: String,
    },
    /// Operator (or VAD) interrupted the agent mid-response. The
    /// SPA flushes any in-flight audio playback; the runner halts
    /// the LLM stream and TTS synthesis.
    VoiceInterrupted {
        session: String,
        /// One of "operator_barge_in" | "vad_speech_detected".
        reason: String,
    },

    // ---- C4 — generic Card primitive (deep research, future
    // shell-session / file-pipeline tools all share this surface) ---
    /// A new Card is being opened on the conversation. Carries the
    /// full opened payload so the SPA's card-store can `fromOpened`
    /// without an extra fetch. Mirrors `EventKind::CardOpened` from
    /// the event log; the WS surface is the live channel + the log
    /// is the durable source of truth.
    CardOpened {
        conversation_id: String,
        card_id: String,
        /// Lowercase kind: "research" / "long_running_task" / etc.
        card_kind: String,
        title: String,
        summary: String,
        state: Option<String>,
        details: serde_json::Value,
        actions: serde_json::Value,
        committed_at: i64,
        /// 2026-05-03 — assigned `state_events.seq` so the SPA can
        /// place the card inline in the chat-thread timeline at
        /// the same position it occupies in the durable event log
        /// (instead of falling back to a synthetic timestamp-based
        /// sortKey that always pinned cards to the bottom).
        event_seq: i64,
    },

    /// A Card progressed — partial update (every field optional;
    /// projection merges populated fields onto the live row). The
    /// SPA's per-kind renderer reads `details` to paint kind-specific
    /// state (e.g. ResearchCard reads `details.notes` for the
    /// per-sub-query badges).
    CardProgressed {
        conversation_id: String,
        card_id: String,
        state: Option<String>,
        progress: Option<f32>,
        phase: Option<String>,
        details: Option<serde_json::Value>,
        actions: Option<serde_json::Value>,
        summary: Option<String>,
        committed_at: i64,
        event_seq: i64,
    },

    /// A Card reached its terminal state. SPA flips inline-render
    /// from "live" to "summary + actions"; transports may invoke
    /// `send_file` if `attachment_id` is populated (C5 wires that).
    CardClosed {
        conversation_id: String,
        card_id: String,
        state: String,
        summary: String,
        details: Option<serde_json::Value>,
        attachment_id: Option<String>,
        error: Option<String>,
        committed_at: i64,
        event_seq: i64,
    },
}

/// Broadcast channel capacity. Lagging subscribers drop the oldest
/// events (broadcast's default behavior), which is fine — the UI uses
/// the event log for canonical state.
const CHANNEL_CAPACITY: usize = 256;

/// Handle that publishers use to fan-out `UiEvent`s to every live
/// WebSocket subscriber.
#[derive(Clone, Debug)]
pub struct EventBus {
    tx: broadcast::Sender<UiEvent>,
}

impl EventBus {
    pub fn new() -> Self {
        let (tx, _rx) = broadcast::channel(CHANNEL_CAPACITY);
        Self { tx }
    }

    /// Broadcast an event. Swallows "no receivers" since it's expected
    /// to happen before any UI connects.
    pub fn publish(&self, ev: UiEvent) {
        let _ = self.tx.send(ev);
    }

    /// Create a new subscriber. Returns the receiver only; callers must
    /// hold it for the duration they want to observe events.
    pub fn subscribe(&self) -> broadcast::Receiver<UiEvent> {
        self.tx.subscribe()
    }

    /// Current subscriber count — useful for health probes.
    pub fn subscriber_count(&self) -> usize {
        self.tx.receiver_count()
    }
}

impl Default for EventBus {
    fn default() -> Self {
        Self::new()
    }
}

