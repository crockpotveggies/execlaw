-- Phase 14 follow-up — repair `config_backends.model_spec_json`
-- rows whose storage class drifted from BLOB to TEXT under the
-- buggy first cut of migration 0020.
--
-- Background: 0020's first revision used
-- `UPDATE … SET model_spec_json = json_set(…)` directly.
-- `json_set()` returns TEXT; SQLite stores the result with TEXT
-- affinity, even on a column declared `BLOB NOT NULL`. The
-- BackendStore's read code expects bytes (`row.get::<_, Vec<u8>>`)
-- and rejects TEXT cells with `Invalid column type`. The result:
-- after the buggy 0020 ran, the supervisor's `list_backends()` call
-- failed every reconcile pass, parking every managed row in
-- "no work scheduled" state.
--
-- 0020 has been fixed in-place to wrap the inner `json_set()` in
-- `CAST(… AS BLOB)`, but its id is already recorded in
-- `_migrations` on any DB that ran the buggy version, so a re-run
-- is a no-op. This migration walks the table once and casts every
-- row's `model_spec_json` back to BLOB. Safe to run on a
-- never-broken DB — `CAST(blob AS BLOB)` is a byte-identity
-- operation, and on a TEXT cell it interprets the UTF-8 bytes as a
-- blob (which is exactly what we want, since the JSON was already
-- valid UTF-8).
UPDATE config_backends
SET model_spec_json = CAST(model_spec_json AS BLOB);
