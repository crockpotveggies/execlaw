//! One-shot tool: apply every embedded migration to a fresh
//! in-memory SQLite, then emit the resulting schema as a single
//! squashable baseline migration.
//!
//! Captures:
//!   * Every table / index / trigger / view created by any
//!     migration in `MIGRATIONS` (read from `sqlite_master`,
//!     so post-ALTER shapes win).
//!   * Seeded rows in any table that holds a singleton or a
//!     small set of defaults (config_general, etc.). We detect
//!     "seeded" by looking at what's present after apply_all
//!     against an empty DB — a non-empty table at that point
//!     was populated by migration SQL, not by an operator.
//!
//! Run:
//!     cargo run -p execlaw-core --bin dump_baseline_schema \
//!        > crates/core/migrations/0001_baseline.sql
//!
//! Ordering: tables first (by name), then indexes, then
//! triggers, then INSERTs. SQLite is permissive about FK order
//! during CREATE since constraints are deferred to commit time;
//! we don't need topological sorting.

use execlaw_core::Database;
use execlaw_core::MigrationRunner;
use execlaw_core::db::DbConfig;

fn main() {
    let db = Database::open(&DbConfig::in_memory_unencrypted())
        .expect("open in-memory db");
    MigrationRunner::new(&db)
        .apply_all()
        .expect("apply_all should succeed on a fresh db");

    let mut out = String::new();
    out.push_str(
        "-- Squashed baseline (replaces 0001..0036).\n\
         --\n\
         -- This file is generated by `cargo run -p execlaw-core --bin\n\
         -- dump_baseline_schema` against a fresh DB after applying\n\
         -- the historical migration chain. Do NOT edit it by hand —\n\
         -- changes to the live schema land in NEW migration files\n\
         -- (0002, 0003, …) just like before. The baseline is\n\
         -- immutable once shipped.\n\
         --\n\
         -- Operators upgrading from a pre-baseline install: this\n\
         -- repo is pre-v1 and the operator has explicitly accepted\n\
         -- a one-time `rm execlaw.db` to land on the baseline\n\
         -- cleanly. Any future schema change uses a normal\n\
         -- additive migration on top of this file.\n\n",
    );

    db.with_conn(|c| {
        // ---- Tables ----------------------------------------------------
        //
        // FTS5 shadow tables (`<vt>_config`, `<vt>_data`,
        // `<vt>_docsize`, `<vt>_idx`, `<vt>_content`, `<vt>_segments`,
        // `<vt>_segdir`) are auto-created by SQLite when the
        // `CREATE VIRTUAL TABLE … USING fts5(…)` runs, but they
        // ALSO show up in `sqlite_master` with synthesized
        // `CREATE TABLE 'foo_config'(…)` SQL. If we emit them in
        // the baseline file they conflict with the virtual table's
        // auto-creation. Detect by the synthesized SQL signature
        // (single-quoted table name, which sqlite never emits for
        // user-defined tables) and skip.
        let mut stmt = c
            .prepare(
                "SELECT name, sql FROM sqlite_master \
                 WHERE type = 'table' \
                   AND name NOT LIKE 'sqlite_%' \
                   AND name != 'schema_version' \
                 ORDER BY name",
            )?;
        let raw_tables: Vec<(String, String)> = stmt
            .query_map([], |r| {
                let name: String = r.get(0)?;
                let sql: Option<String> = r.get(1)?;
                Ok((name, sql.unwrap_or_default()))
            })?
            .collect::<Result<_, _>>()?;
        let tables: Vec<(String, String)> = raw_tables
            .into_iter()
            .filter(|(_, sql)| {
                // FTS5 shadow tables (`<vt>_config` etc.) — sqlite
                // auto-creates them when the virtual table is
                // created and emits their `sql` column with the
                // table name single-quoted, which user-defined
                // tables never do. Skip them so the baseline
                // doesn't fight the virtual-table CREATE.
                !sql.trim_start().starts_with("CREATE TABLE '")
            })
            .collect();
        out.push_str("-- =========================================================================\n");
        out.push_str("-- TABLES\n");
        out.push_str("-- =========================================================================\n\n");
        for (_, sql) in &tables {
            if sql.is_empty() {
                continue;
            }
            out.push_str(sql.trim());
            out.push_str(";\n\n");
        }

        // ---- Indexes (skip auto-indexes for PK/UNIQUE) ---------------
        let mut stmt = c.prepare(
            "SELECT sql FROM sqlite_master \
             WHERE type = 'index' \
               AND sql IS NOT NULL \
               AND name NOT LIKE 'sqlite_%' \
             ORDER BY name",
        )?;
        let indexes: Vec<String> = stmt
            .query_map([], |r| r.get::<_, String>(0))?
            .collect::<Result<_, _>>()?;
        if !indexes.is_empty() {
            out.push_str("-- =========================================================================\n");
            out.push_str("-- INDEXES\n");
            out.push_str("-- =========================================================================\n\n");
            for sql in &indexes {
                out.push_str(sql.trim());
                out.push_str(";\n");
            }
            out.push('\n');
        }

        // ---- Triggers --------------------------------------------------
        let mut stmt = c.prepare(
            "SELECT sql FROM sqlite_master \
             WHERE type = 'trigger' \
               AND sql IS NOT NULL \
             ORDER BY name",
        )?;
        let triggers: Vec<String> = stmt
            .query_map([], |r| r.get::<_, String>(0))?
            .collect::<Result<_, _>>()?;
        if !triggers.is_empty() {
            out.push_str("-- =========================================================================\n");
            out.push_str("-- TRIGGERS\n");
            out.push_str("-- =========================================================================\n\n");
            for sql in &triggers {
                out.push_str(sql.trim());
                out.push_str(";\n\n");
            }
        }

        // ---- Views -----------------------------------------------------
        let mut stmt = c.prepare(
            "SELECT sql FROM sqlite_master \
             WHERE type = 'view' \
               AND sql IS NOT NULL \
             ORDER BY name",
        )?;
        let views: Vec<String> = stmt
            .query_map([], |r| r.get::<_, String>(0))?
            .collect::<Result<_, _>>()?;
        if !views.is_empty() {
            out.push_str("-- =========================================================================\n");
            out.push_str("-- VIEWS\n");
            out.push_str("-- =========================================================================\n\n");
            for sql in &views {
                out.push_str(sql.trim());
                out.push_str(";\n\n");
            }
        }

        // ---- Seeded rows ----------------------------------------------
        // A non-empty table after apply_all on an empty DB was seeded
        // by migration SQL. Capture those rows as INSERT OR IGNORE
        // so the baseline reproduces the same starting state.
        out.push_str("-- =========================================================================\n");
        out.push_str("-- SEEDED ROWS\n");
        out.push_str("-- =========================================================================\n\n");
        for (table, _) in &tables {
            // Count rows; emit INSERTs only for non-empty tables.
            let count: i64 = c
                .query_row(&format!("SELECT COUNT(*) FROM \"{table}\""), [], |r| {
                    r.get(0)
                })?;
            if count == 0 {
                continue;
            }

            // Pull column names for ordered INSERTs.
            let mut col_stmt = c.prepare(&format!("PRAGMA table_info(\"{table}\")"))?;
            let cols: Vec<String> = col_stmt
                .query_map([], |r| r.get::<_, String>(1))?
                .collect::<Result<_, _>>()?;

            let select_sql = format!(
                "SELECT {} FROM \"{table}\"",
                cols.iter()
                    .map(|c| format!("\"{c}\""))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
            let mut row_stmt = c.prepare(&select_sql)?;
            let rows: Vec<Vec<rusqlite::types::Value>> = row_stmt
                .query_map([], |r| {
                    let mut row = Vec::with_capacity(cols.len());
                    for i in 0..cols.len() {
                        row.push(r.get::<_, rusqlite::types::Value>(i)?);
                    }
                    Ok(row)
                })?
                .collect::<Result<_, _>>()?;

            for row in &rows {
                let values: Vec<String> = row.iter().map(format_sqlite_value).collect();
                out.push_str(&format!(
                    "INSERT OR IGNORE INTO \"{table}\" ({}) VALUES ({});\n",
                    cols.iter()
                        .map(|c| format!("\"{c}\""))
                        .collect::<Vec<_>>()
                        .join(", "),
                    values.join(", ")
                ));
            }
            if !rows.is_empty() {
                out.push('\n');
            }
        }

        Ok(())
    })
    .expect("dump");

    print!("{out}");
}

fn format_sqlite_value(v: &rusqlite::types::Value) -> String {
    use rusqlite::types::Value;
    match v {
        Value::Null => "NULL".to_owned(),
        Value::Integer(i) => i.to_string(),
        Value::Real(f) => f.to_string(),
        Value::Text(s) => format!("'{}'", s.replace('\'', "''")),
        Value::Blob(b) => {
            let hex = b.iter().map(|x| format!("{x:02x}")).collect::<String>();
            format!("X'{hex}'")
        }
    }
}
